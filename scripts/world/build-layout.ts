/**
 * Writes src/world/placement/layout.generated.ts from the registry.
 *
 *   node --experimental-strip-types scripts/world/build-layout.ts   (npm run build:layout)
 *
 * Deterministic for the registry and the seed; the output is committed so a
 * change in placement is a reviewable diff (PRD §9.4).
 */
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { REGISTRY } from '../../src/lib/world/registry/subindustries.generated.ts';
import { placeWorld } from '../../src/world/placement/place.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const regSha = createHash('sha256').update(fs.readFileSync(path.join(ROOT, 'src/lib/world/registry/subindustries.generated.ts'))).digest('hex');
const layout = placeWorld(REGISTRY, 20261004, regSha);
const out = `// GENERATED by scripts/world/build-layout.ts from the registry (sha256 ${regSha}) — do not edit by hand.
import type { GeneratedLayout } from './types';

export const LAYOUT: GeneratedLayout = ${JSON.stringify(layout, null, 1)};
`;
const target = path.join(ROOT, 'src/world/placement/layout.generated.ts');
const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8') === out;
if (!same) fs.writeFileSync(target, out);
console.log(`build-layout: ${layout.blocks.length} blocks · ${layout.roads.length} roads · ${layout.gates.length} gates · ${layout.signposts.length} signposts · ${layout.fixtures.length} fixtures · ${same ? 'unchanged' : 'written'}`);
