#!/usr/bin/env node
/**
 * The tracker's seed migration, written from supabase/content/tracker_entries.json.
 *
 * The JSON is the reviewable source: its entry text is copied from the
 * signed-off Part A of docs/spec/tracker_sources.md, and each entry names its
 * sources by key. The migration stores each entry's sources in full, as the
 * `sources jsonb` column holds them (PRD §B4), so the key lookup happens here
 * and nowhere else.
 *
 *   node scripts/tracker/seed.mjs          rewrite the migration
 *   node scripts/tracker/seed.mjs --check  exit 1 if it is out of date
 *
 * tests/unit/tracker_copy.test.ts runs the same comparison in CI.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
export const CONTENT_PATH = join(ROOT, 'supabase/content/tracker_entries.json');
export const SEED_PATH = join(ROOT, 'supabase/migrations/20261011100100_tracker_entry_seed.sql');

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

/** An entry's sources, resolved from keys to the objects the column stores. */
export function resolveSources(content, entry) {
  return entry.sources.map((key) => {
    const source = content.sources[key];
    if (!source) throw new Error(`${entry.id}: unknown source key "${key}"`);
    return source;
  });
}

export function buildSeedSql(content) {
  const rows = content.entries.map((e) => {
    const sources = JSON.stringify(resolveSources(content, e));
    return [
      `  (${lit(e.id)}, ${lit(e.quarter)}, ${lit(e.sector)}, ${lit(e.status)},`,
      `   ${lit(e.finding)},`,
      `   ${lit(e.detail)},`,
      `   ${lit(sources)}::jsonb,`,
      `   ${lit(e.verification)}, ${e.published ? 'true' : 'false'})`,
    ].join('\n');
  });
  return `-- =============================================================================
-- The Green Transition Tracker register, Q1 and Q2 2025 (Plan 2.2).
--
-- GENERATED by scripts/tracker/seed.mjs from supabase/content/tracker_entries.json.
-- Do not edit by hand: change the JSON and rerun the script.
-- tests/unit/tracker_copy.test.ts fails if the two disagree.
--
-- Fourteen entries, signed off by Dika on 11 October 2026
-- (docs/spec/tracker_sources.md, Part A). Every row lands with
-- published = false; a later migration sets it to true once the page has
-- been reviewed on the preview deployment (PRD §B6).
--
-- ON CONFLICT (id) DO NOTHING: rerunning the file, or a row edited since,
-- changes nothing.
--
-- DOWN: DELETE FROM public.tracker_entry WHERE id IN (the fourteen ids below);
-- =============================================================================

INSERT INTO public.tracker_entry
  (id, quarter, sector, status, finding, detail, sources, verification, published)
VALUES
${rows.join(',\n')}
ON CONFLICT (id) DO NOTHING;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const content = JSON.parse(readFileSync(CONTENT_PATH, 'utf8'));
  const sql = buildSeedSql(content);
  if (process.argv.includes('--check')) {
    const current = readFileSync(SEED_PATH, 'utf8');
    if (current !== sql) {
      console.error('tracker seed: migration is out of date; run node scripts/tracker/seed.mjs');
      process.exit(1);
    }
    console.log('tracker seed: up to date');
  } else {
    writeFileSync(SEED_PATH, sql);
    console.log(`tracker seed: wrote ${content.entries.length} rows`);
  }
}
